public class MayorMenor {
    public static void main(String[] args) {
        int numero = -14;

        if (numero > 0) {
            System.out.println(numero + " es mayor que 0"); 
        } else if (numero == 0) {
            System.out.println(numero + " es igual a 0"); 
        } else {
            System.out.println(numero + " es menor a 0"); 
        }
    }
}